-- community-service 첫 스키마. Hibernate ddl-auto: update가 만들던 테이블을 그대로 옮겼다.
-- 스키마 이름은 쓰지 않는다. Flyway가 spring.flyway.default-schema(community_service)를 기준으로 실행한다.

create table posts (
    post_id bigint generated by default as identity,
    user_id bigint not null,
    post_type varchar(20) not null,
    category varchar(30) not null,
    title varchar(255) not null,
    content text not null,
    view_count bigint not null,
    shared_type varchar(20),
    shared_id bigint,
    shared_product_id bigint,
    shared_brand_name varchar(100),
    shared_product_name varchar(255),
    shared_price integer,
    shared_image_url varchar(500),
    shared_summary text,
    vote_end_at timestamp(6) with time zone,
    vote_closed boolean default false not null,
    vote_close_notification_pending boolean default false not null,
    vote_close_notify_failed_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,
    version bigint default 0 not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint posts_pkey primary key (post_id),
    constraint posts_post_type_check check (post_type in ('NORMAL', 'VOTE')),
    constraint posts_category_check check (category in ('FASHION', 'COORDI_QUESTION', 'DAILY')),
    constraint posts_shared_type_check check (shared_type in ('WORLDCUP', 'COMBO', 'FITTING', 'PRODUCT'))
);

-- 공유한 코디·피팅 결과에 들어 있던 상품들(공유 당시 순서대로). 월드컵·상품 공유는 비어 있다.
create table post_shared_items (
    post_id bigint not null,
    item_order integer not null,
    product_id bigint,
    product_name varchar(255),
    price integer,
    image_url varchar(500),
    constraint post_shared_items_pkey primary key (post_id, item_order),
    constraint fk_post_shared_items_post foreign key (post_id) references posts (post_id)
);

create table post_likes (
    post_id bigint not null,
    user_id bigint not null,
    created_at timestamp(6) with time zone not null,
    constraint post_likes_pkey primary key (post_id, user_id)
);

create table comments (
    comment_id bigint generated by default as identity,
    post_id bigint not null,
    user_id bigint not null,
    content text not null,
    parent_comment_id bigint,
    is_deleted boolean not null,
    supported_option_id bigint,
    version bigint default 0 not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint comments_pkey primary key (comment_id)
);

create table comment_likes (
    comment_id bigint not null,
    user_id bigint not null,
    created_at timestamp(6) with time zone not null,
    constraint comment_likes_pkey primary key (comment_id, user_id)
);

create table vote_options (
    vote_option_id bigint generated by default as identity,
    post_id bigint not null,
    item_id varchar(100),
    item_type varchar(20) not null,
    source varchar(20) not null,
    image_url varchar(500) not null,
    snapshot_name varchar(255),
    snapshot_price integer,
    display_order integer not null,
    constraint vote_options_pkey primary key (vote_option_id),
    constraint uk_vote_options_post_item unique (post_id, item_id, item_type),
    constraint vote_options_item_type_check check (item_type in ('PRODUCT', 'COMBO')),
    constraint vote_options_source_check check (source in ('AI_RECOMMEND', 'WISHLIST'))
);

create table votes (
    vote_id varchar(36) not null,
    post_id bigint not null,
    user_id bigint not null,
    vote_option_id bigint not null,
    created_at timestamp(6) with time zone not null,
    constraint votes_pkey primary key (vote_id),
    constraint uk_votes_post_user unique (post_id, user_id)
);
