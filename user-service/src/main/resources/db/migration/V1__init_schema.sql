-- user-service 첫 스키마. Hibernate ddl-auto: update가 만들던 테이블을 그대로 옮겼다.
-- 스키마 이름은 쓰지 않는다. Flyway가 spring.flyway.default-schema(user_service)를 기준으로 실행한다.

create table users (
    user_id bigint generated by default as identity,
    email varchar(255) not null,
    password varchar(255) not null,
    nickname varchar(50) not null,
    status varchar(20) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint users_pkey primary key (user_id),
    constraint uk_users_email unique (email),
    constraint uk_users_nickname unique (nickname),
    constraint users_status_check check (status in ('ACTIVE', 'SUSPENDED', 'DELETED'))
);

create table user_body (
    user_id bigint not null,
    height float(24),
    weight float(24),
    gender varchar(1),
    preferred_styles varchar(255),
    preferred_fit varchar(50),
    shoe_size integer,
    updated_at timestamp(6) with time zone not null,
    constraint user_body_pkey primary key (user_id)
);
