-- review-service 첫 스키마. Hibernate ddl-auto: update가 만들던 테이블을 그대로 옮겼다.
-- 스키마 이름은 쓰지 않는다. Flyway가 spring.flyway.default-schema(review_service)를 기준으로 실행한다.

create table reviews (
    review_id bigint generated by default as identity,
    user_id bigint not null,
    product_id bigint not null,
    order_item_id bigint not null,
    rating integer not null,
    content text not null,
    image_url varchar(500),
    version bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint reviews_pkey primary key (review_id),
    constraint uk_reviews_order_item unique (order_item_id)
);

create index idx_reviews_product_created on reviews (product_id, created_at);

create table size_surveys (
    survey_id bigint generated by default as identity,
    user_id bigint not null,
    product_id bigint,
    option_id bigint not null,
    order_item_id bigint not null,
    size_feedback varchar(10) not null,
    created_at timestamp(6) with time zone not null,
    feedback_sent_at timestamp(6) with time zone,
    feedback_claimed_at timestamp(6) with time zone,
    constraint size_surveys_pkey primary key (survey_id),
    constraint uk_size_surveys_user_order_item unique (user_id, order_item_id),
    constraint size_surveys_size_feedback_check check (size_feedback in ('SMALL', 'FIT', 'BIG'))
);
